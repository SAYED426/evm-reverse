/**
 * Output assembly: swap Heimdall's placeholder names for resolved signatures and
 * wrap the result with an honest header describing what this file is.
 */

import type { ProxyInfo } from "./proxy.ts";
import type { ResolvedSignature } from "./selectors.ts";

export interface EmitMetadata {
  address: string;
  chainId: number;
  blockNumber: number;
  generatedAt: string;
  rpc: string;
  proxy: ProxyInfo;
  /** What was decompiled: "address", "implementation", "proxy", or "raw". */
  targetKind: string;
  resolvedFunctions: number;
  unresolvedFunctions: number;
  resolvedEvents: number;
  unresolvedEvents: number;
  /** Present when the LLM readability pass ran. */
  llm?: { model: string; notes: string[] };
}

const SEP = "// " + "─".repeat(74);

function proxyLines(proxy: ProxyInfo): string {
  if (!proxy.isProxy) return "// Proxy:            no";
  const lines = [`// Proxy:            yes (${proxy.kind})`];
  if (proxy.implementation) lines.push(`// Implementation:   ${proxy.implementation}`);
  if (proxy.beacon) lines.push(`// Beacon:           ${proxy.beacon}`);
  if (proxy.admin) lines.push(`// Admin:            ${proxy.admin}`);
  return lines.join("\n");
}

export function buildHeader(meta: EmitMetadata, contractName: string): string {
  return [
    SEP,
    "//  DECOMPILED CONTRACT — NOT ORIGINAL SOURCE",
    SEP,
    "//",
    "//  This Solidity was reconstructed from on-chain EVM bytecode. It is an",
    "//  approximation: function selectors and signatures are recovered from public",
    "//  signature databases, control flow is reconstructed by symbolic execution,",
    "//  and identifiers carry no meaning from the original project.",
    "//",
    "//  Expect:  correct-ish logic, real selectors, plausible storage layout.",
    "//  Do not expect: original names, comments, custom errors, or exact syntax.",
    "//  Treat as a map of the contract, not a reproduction of it.",
    "//",
    `// Contract:          ${contractName}`,
    `// Address:           ${meta.address}`,
    `// Chain ID:          ${meta.chainId}`,
    `// Block:             ${meta.blockNumber}`,
    `// Generated:         ${meta.generatedAt}`,
    proxyLines(meta.proxy),
    `// RPC:               ${meta.rpc}`,
    "//",
    `// Resolved:          ${meta.resolvedFunctions} function(s), ${meta.resolvedEvents} event(s)`,
    `// Unresolved:        ${meta.unresolvedFunctions} function(s), ${meta.unresolvedEvents} event(s)`,
    ...(meta.llm
      ? [
          "//",
          `// LLM readability pass by ${meta.llm.model}: identifiers renamed and comments added.`,
          "//   This pass can alter detail; the raw decompilation is the faithful reference.",
        ]
      : []),
    "//",
    "// Generated by evm-reverse (Heimdall decompiler + OpenChain/4byte resolution).",
    SEP,
  ].join("\n");
}

function escapeRegExp(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/** Pull the parameter type list out of a signature like `Transfer(address,uint256)`. */
function paramsOf(signature: string): string | null {
  const open = signature.indexOf("(");
  const close = signature.lastIndexOf(")");
  if (open === -1 || close === -1 || close <= open) return null;
  const params = signature.slice(open + 1, close).trim();
  return params.length > 0 ? params : null;
}

/**
 * Replace Heimdall's placeholder names with resolved signatures.
 *
 * Two placeholder forms appear: `Unresolved_deadbeef` for functions and public
 * getters, and `Event_deadbeef` for events. Resolved events also gain their
 * parameter list, which Heimdall omits.
 */
export function applyResolvedNames(
  sol: string,
  functions: Map<string, ResolvedSignature>,
  events: Map<string, ResolvedSignature>,
): string {
  let out = sol;

  for (const [selector, sig] of functions) {
    const hex = selector.replace(/^0x/, "");
    out = out.replace(new RegExp(`[Uu]nresolved_${hex}\\b`, "g"), sig.name);
    out = out.replace(
      new RegExp(`(/// @custom:signature\\s+)[Uu]nresolved_${hex}`, "g"),
      `$1${sig.signature}`,
    );
  }

  for (const [selector, sig] of events) {
    const hex = selector.replace(/^0x/, "");
    out = out.replace(new RegExp(`Event_${hex}\\b`, "g"), sig.name);
    const params = paramsOf(sig.signature);
    if (params) {
      out = out.replace(
        new RegExp(`event\\s+${escapeRegExp(sig.name)}\\(\\);`, "g"),
        `event ${sig.name}(${params});`,
      );
    }
  }

  return out;
}

/** Keep the pragma, drop Heimdall's own banner, and return the contract body. */
export function extractCode(rawSol: string): string {
  const match = /^contract\s+\w+/m.exec(rawSol);
  const body = match ? rawSol.slice(match.index) : rawSol;
  return body.replace(/\u0000/g, "");
}

/** Assemble final output from an already-extracted code body plus our header. */
export function composeFromCode(code: string, header: string): string {
  return `// SPDX-License-Identifier: UNLICENSED\npragma solidity >=0.8.0;\n\n${header}\n\n${code}`.trimEnd() + "\n";
}

/** Keep the pragma, drop Heimdall's own banner, and prepend ours. */
export function composeSolidity(rawSol: string, header: string): string {
  return composeFromCode(extractCode(rawSol), header);
}

export function contractNameFrom(address: string): string {
  return `Decompiled_${address.slice(2, 10)}`;
}
